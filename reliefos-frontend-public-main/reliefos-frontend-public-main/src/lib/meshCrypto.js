/**
 * src/lib/meshCrypto.js
 *
 * Pure Web Crypto implementation. No external libraries.
 * Labels: "Encryption: real (Web Crypto, ECDH P-256 + AES-GCM)"
 *         "Radio: simulated"
 *
 * Flow per UI_SPEC screen 8:
 *   1. Gateway generates an ECDH P-256 key pair (public key shared out-of-band).
 *   2. Sender (Volunteer 1) generates a one-shot ECDH key pair and derives a
 *      shared AES-GCM key via ECDH with the Gateway's public key.
 *   3. Message is encrypted with AES-GCM (random 12-byte IV).
 *   4. Ciphertext hops Volunteer 1 → 2 → 3 → Gateway (relay nodes see only ciphertext).
 *   5. Gateway decrypts using its private key + Sender's ephemeral public key.
 */

const subtle = window.crypto.subtle;

// ─── Helpers ─────────────────────────────────────────────────────────────────

/** ArrayBuffer → Base64 string */
function bufToB64(buf) {
  return btoa(String.fromCharCode(...new Uint8Array(buf)));
}

/** Base64 string → Uint8Array */
function b64ToBuf(b64) {
  const binary = atob(b64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes;
}

/** UTF-8 string → ArrayBuffer */
function strToBuf(str) {
  return new TextEncoder().encode(str);
}

/** ArrayBuffer → UTF-8 string */
function bufToStr(buf) {
  return new TextDecoder().decode(buf);
}

// ─── Key generation ──────────────────────────────────────────────────────────

/**
 * Generate a Gateway ECDH P-256 key pair.
 * @returns {Promise<{ keyPair: CryptoKeyPair, publicKeyB64: string }>}
 */
export async function generateGatewayKeyPair() {
  const keyPair = await subtle.generateKey(
    { name: 'ECDH', namedCurve: 'P-256' },
    true,   // extractable (so we can share the public key)
    ['deriveKey']
  );

  const rawPublic = await subtle.exportKey('raw', keyPair.publicKey);
  const publicKeyB64 = bufToB64(rawPublic);

  return { keyPair, publicKeyB64 };
}

// ─── Encrypt (Sender / Volunteer 1) ─────────────────────────────────────────

/**
 * Encrypt `plaintext` for the Gateway identified by `gatewayPublicKeyB64`.
 *
 * Returns everything the relay chain (and eventually Gateway) needs:
 *   - ciphertextB64    — AES-GCM ciphertext, base64
 *   - ivB64            — 12-byte IV, base64
 *   - senderPublicKeyB64 — sender's ephemeral ECDH public key, base64
 *
 * @param {string} plaintext
 * @param {string} gatewayPublicKeyB64
 * @returns {Promise<{ ciphertextB64: string, ivB64: string, senderPublicKeyB64: string }>}
 */
export async function encryptMessage(plaintext, gatewayPublicKeyB64) {
  // 1. Import Gateway's public key
  const gatewayPublicKey = await subtle.importKey(
    'raw',
    b64ToBuf(gatewayPublicKeyB64),
    { name: 'ECDH', namedCurve: 'P-256' },
    false,
    []  // public key: no usages needed for ECDH import
  );

  // 2. Generate sender's ephemeral ECDH key pair
  const senderKeyPair = await subtle.generateKey(
    { name: 'ECDH', namedCurve: 'P-256' },
    true,
    ['deriveKey']
  );

  const rawSenderPublic = await subtle.exportKey('raw', senderKeyPair.publicKey);
  const senderPublicKeyB64 = bufToB64(rawSenderPublic);

  // 3. Derive AES-GCM shared key via ECDH
  const sharedKey = await subtle.deriveKey(
    { name: 'ECDH', public: gatewayPublicKey },
    senderKeyPair.privateKey,
    { name: 'AES-GCM', length: 256 },
    false,
    ['encrypt']
  );

  // 4. Encrypt with AES-GCM (random 12-byte IV)
  const iv = window.crypto.getRandomValues(new Uint8Array(12));
  const ciphertext = await subtle.encrypt(
    { name: 'AES-GCM', iv },
    sharedKey,
    strToBuf(plaintext)
  );

  return {
    ciphertextB64: bufToB64(ciphertext),
    ivB64: bufToB64(iv),
    senderPublicKeyB64,
  };
}

// ─── Decrypt (Gateway) ───────────────────────────────────────────────────────

/**
 * Decrypt a message received at the Gateway.
 *
 * @param {{ ciphertextB64: string, ivB64: string, senderPublicKeyB64: string }} packet
 * @param {CryptoKeyPair} gatewayKeyPair  — the pair generated by generateGatewayKeyPair()
 * @returns {Promise<string>} plaintext
 */
export async function decryptMessage(packet, gatewayKeyPair) {
  const { ciphertextB64, ivB64, senderPublicKeyB64 } = packet;

  // 1. Import sender's ephemeral public key
  const senderPublicKey = await subtle.importKey(
    'raw',
    b64ToBuf(senderPublicKeyB64),
    { name: 'ECDH', namedCurve: 'P-256' },
    false,
    []
  );

  // 2. Derive the same AES-GCM shared key using Gateway's private key
  const sharedKey = await subtle.deriveKey(
    { name: 'ECDH', public: senderPublicKey },
    gatewayKeyPair.privateKey,
    { name: 'AES-GCM', length: 256 },
    false,
    ['decrypt']
  );

  // 3. Decrypt
  const plaintext = await subtle.decrypt(
    { name: 'AES-GCM', iv: b64ToBuf(ivB64) },
    sharedKey,
    b64ToBuf(ciphertextB64)
  );

  return bufToStr(plaintext);
}
